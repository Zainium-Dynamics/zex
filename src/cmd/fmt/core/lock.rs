//! Generates the `.zex.locked` companion artifact: the full,
//! un-obfuscated source tree plus five maintainer review slots that
//! must all be `Approved` before the corresponding `.zex` binary is
//! trusted for the official Zainium repository.
//!
//! `.zex.locked` is never shipped to end users — installers only ever
//! handle the compiled, locked-down `.zex` binary. `.zex.locked` stays
//! inside the maintainer review pipeline so a maintainer can read the
//! real source (and the full Rust/clippy/audit report) before signing
//! off, without end users being able to "extract and tamper" a binary
//! release and re-pack it as if it were official.

use crate::cmd::fmt::core::manifest::{ZexTomlManifest as Manifest, ZexTomlManifest};
use crate::cmd::fmt::core::report::SecurityReport;
use crate::cmd::fmt::error::Result;
use crate::cmd::fmt::utils::compressor;
use serde::{Deserialize, Serialize};
use std::io::Write;
use std::path::Path;

pub const REQUIRED_APPROVALS: usize = 5;

#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize)]
#[serde(rename_all = "snake_case")]
pub enum ReviewStatus {
    Pending,
    Approved,
    ChangesRequested,
    Rejected,
}

#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct MaintainerReview {
    pub slot: u8,
    pub reviewer: Option<String>,
    pub status: ReviewStatus,
    pub notes: Option<String>,
    pub reviewed_at: Option<chrono::DateTime<chrono::Utc>>,
}

impl MaintainerReview {
    fn empty(slot: u8) -> Self {
        MaintainerReview {
            slot,
            reviewer: None,
            status: ReviewStatus::Pending,
            notes: None,
            reviewed_at: None,
        }
    }
}

#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct LockedManifest {
    pub schema: String,
    pub package_name: String,
    pub package_version: String,
    pub required_approvals: usize,
    /// The full security report (layout, content, manifest integrity,
    /// permission audit, rust audit) embedded so a maintainer can read
    /// it directly from the locked file without unpacking the binary.
    pub security_report: SecurityReport,
    pub reviews: Vec<MaintainerReview>,
}

impl LockedManifest {
    pub fn new(manifest: &ZexTomlManifest, report: &SecurityReport) -> Self {
        LockedManifest {
            schema: "zainium-locked-source-v1".to_string(),
            package_name: manifest.package.name.clone(),
            package_version: manifest.package.version.clone(),
            required_approvals: REQUIRED_APPROVALS,
            security_report: report.clone(),
            reviews: (1..=REQUIRED_APPROVALS as u8)
                .map(MaintainerReview::empty)
                .collect(),
        }
    }

    pub fn approvals_count(&self) -> usize {
        self.reviews
            .iter()
            .filter(|r| r.status == ReviewStatus::Approved)
            .count()
    }

    pub fn is_fully_approved(&self) -> bool {
        self.approvals_count() >= self.required_approvals
            && self
                .reviews
                .iter()
                .all(|r| r.status != ReviewStatus::Rejected)
    }

    /// Renders the human-facing maintainer review document. This is the
    /// canonical "review engine" format: every `.zex.locked` ships with
    /// this exact structure (machine-readable JSON header is the source
    /// of truth; this markdown is the rendered checklist a maintainer
    /// actually reads/signs off on). One section per required approval
    /// slot, each with the same fixed checklist so reviews are
    /// comparable across packages and across reviewers.
    pub fn to_review_markdown(&self) -> String {
        let mut md = String::new();
        md.push_str(&format!(
            "# Maintainer Review — {} {}\n\n",
            self.package_name, self.package_version
        ));
        md.push_str(&format!(
            "Schema: `{}` · Required approvals: **{}/{}**\n\n",
            self.schema,
            self.approvals_count(),
            self.required_approvals
        ));
        md.push_str("## Automated audit summary (read-only, generated by zex-fmt)\n\n");
        md.push_str(&format!(
            "- Layout policy: `{:?}`\n",
            self.security_report.layout_check.result
        ));
        md.push_str(&format!(
            "- Manifest integrity: `{:?}`\n",
            self.security_report.manifest_integrity.result
        ));
        let setuid = &self.security_report.permission_audit.setuid_files;
        md.push_str(&format!(
            "- setuid/setgid files: {}\n",
            if setuid.is_empty() {
                "none".to_string()
            } else {
                setuid.join(", ")
            }
        ));
        let ra = &self.security_report.rust_audit;
        if ra.applicable {
            md.push_str(&format!("- Rust build kind: `{:?}`\n", ra.build_kind));
            if let Some(n) = ra.unsafe_block_count {
                md.push_str(&format!("- Unsafe expressions: {n}\n"));
            }
            for t in &ra.tools {
                md.push_str(&format!("- {}: `{:?}` — {}\n", t.tool, t.outcome, t.summary));
            }
        }
        md.push('\n');

        md.push_str("## Reviewer checklist (each of the 5 slots below must independently confirm)\n\n");
        md.push_str("1. Source matches the automated audit summary above — no edits since scan.\n");
        md.push_str("2. No undisclosed network calls, telemetry, or credential exfiltration in source.\n");
        md.push_str("3. `unsafe` blocks (if any) are isolated to a reviewed module and are necessary.\n");
        md.push_str("4. Build/install scripts do not escalate privileges beyond what the package declares.\n");
        md.push_str("5. License and provenance of bundled/vendored code is clear.\n\n");

        for review in &self.reviews {
            md.push_str(&format!("---\n\n### Slot {}\n\n", review.slot));
            md.push_str(&format!(
                "- Reviewer: {}\n",
                review.reviewer.as_deref().unwrap_or("_unassigned_")
            ));
            md.push_str(&format!("- Status: `{:?}`\n", review.status));
            md.push_str(&format!(
                "- Reviewed at: {}\n",
                review
                    .reviewed_at
                    .map(|t| t.to_rfc3339())
                    .unwrap_or_else(|| "_pending_".into())
            ));
            md.push_str(&format!(
                "- Notes: {}\n\n",
                review.notes.as_deref().unwrap_or("_none_")
            ));
        }

        md.push_str(&format!(
            "**Package ships to the Zainium repository only once all {} slots are `Approved` and none are `Rejected`.**\n",
            self.required_approvals
        ));
        md
    }
}

/// File magic for the locked-source container. Distinct from `ZEX1` so
/// tooling never confuses an end-user binary with a maintainer-only
/// review artifact.
pub const LOCKED_MAGIC: &[u8; 4] = b"ZEXL";

/// Builds the `.zex.locked` file next to `output_zex_path`:
/// `ZEXL` magic || u64 LE manifest_len || JSON(LockedManifest) ||
/// zstd-compressed tar of the raw, unmodified source tree.
pub fn write_locked(
    source_dir: &Path,
    manifest: &ZexTomlManifest,
    report: &SecurityReport,
    output_zex_path: &Path,
) -> Result<std::path::PathBuf> {
    let mut tar_buf = Vec::new();
    {
        let mut builder = tar::Builder::new(&mut tar_buf);
        builder
            .append_dir_all(".", source_dir)
            .map_err(crate::cmd::fmt::error::ZexError::Io)?;
        builder.finish().map_err(crate::cmd::fmt::error::ZexError::Io)?;
    }
    let compressed = compressor::compress(&tar_buf, compressor::DEFAULT_LEVEL)?;

    let locked_manifest = LockedManifest::new(manifest, report);
    let manifest_json = serde_json::to_vec(&locked_manifest)?;

    let locked_path = locked_path_for(output_zex_path);
    let mut out = std::fs::File::create(&locked_path)?;
    out.write_all(LOCKED_MAGIC)?;
    out.write_all(&(manifest_json.len() as u64).to_le_bytes())?;
    out.write_all(&manifest_json)?;
    out.write_all(&compressed)?;
    out.flush()?;

    // Human-facing rendering of the same review state, regenerated
    // fresh each pack. Maintainer tooling edits the JSON header inside
    // `.zex.locked` (via read/write helpers below); this .md is for
    // reading in a PR/issue tracker, not for editing directly.
    let review_md_path = locked_path.with_extension("locked.review.md");
    std::fs::write(&review_md_path, locked_manifest.to_review_markdown())?;

    Ok(locked_path)
}

/// `vim_9.1.0-r0.zex` -> `vim_9.1.0-r0.zex.locked`
fn locked_path_for(output_zex_path: &Path) -> std::path::PathBuf {
    let mut s = output_zex_path.as_os_str().to_os_string();
    s.push(".locked");
    std::path::PathBuf::from(s)
}

/// Reads back a `.zex.locked` file's manifest header (without
/// decompressing the embedded source tree) — used by review tooling to
/// display/update reviewer state.
pub fn read_locked_manifest(path: &Path) -> Result<LockedManifest> {
    let buf = std::fs::read(path)?;
    if buf.len() < 12 || &buf[0..4] != LOCKED_MAGIC {
        return Err(crate::cmd::fmt::error::ZexError::InvalidFormat(
            "not a valid .zex.locked file (bad magic)".into(),
        ));
    }
    let manifest_len = u64::from_le_bytes(buf[4..12].try_into().unwrap()) as usize;
    let manifest_json = &buf[12..12 + manifest_len];
    Ok(serde_json::from_slice(manifest_json)?)
}
